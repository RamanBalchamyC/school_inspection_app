-- Tamil Nadu School Inspection: Supabase schema.
-- Run once in Supabase Dashboard -> SQL Editor -> New query -> Run.
-- Replaces the old FastAPI + MySQL backend: Supabase Auth handles users,
-- Row Level Security (RLS) enforces "officers see only their own reports, admins see all".

-- ---------- profiles (name + role for each auth user) ----------
create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  name text not null default '',
  role text not null default 'officer' check (role in ('officer', 'admin')),
  created_at timestamptz not null default now()
);
alter table public.profiles enable row level security;

-- security definer so RLS policies can check the role without recursing into profiles' own RLS.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles where id = auth.uid() and role = 'admin'
  );
$$;
revoke execute on function public.is_admin() from public, anon;
grant execute on function public.is_admin() to authenticated;

drop policy if exists "read own profile or admin" on public.profiles;
create policy "read own profile or admin" on public.profiles
  for select to authenticated
  using (id = (select auth.uid()) or public.is_admin());
-- No insert/update policies: users cannot change their own role.

-- Create a profile automatically when someone signs up.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, name)
  values (new.id, coalesce(left(new.raw_user_meta_data ->> 'name', 150), ''));
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ---------- inspections ----------
create table if not exists public.inspections (
  id uuid primary key default gen_random_uuid(),
  client_id uuid not null unique, -- idempotency key generated by the browser
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  district text not null check (char_length(district) between 1 and 100),
  block text not null check (char_length(block) between 1 and 100),
  school_name text not null check (char_length(school_name) between 1 and 200),
  udise_code text not null check (udise_code ~ '^[0-9]{11}$'),
  school_type text not null check (char_length(school_type) between 1 and 100),
  inspection_date date not null,
  officer_name text not null check (char_length(officer_name) between 1 and 150),
  priority text not null check (priority in ('High', 'Medium', 'Low')),
  remarks text not null default '' check (char_length(remarks) <= 5000),
  details jsonb not null default '{}'::jsonb
    check (jsonb_typeof(details) = 'object' and pg_column_size(details) < 200000),
  created_at timestamptz not null default now()
);
create index if not exists idx_inspections_user on public.inspections (user_id);
create index if not exists idx_inspections_district on public.inspections (district);
create index if not exists idx_inspections_date on public.inspections (inspection_date desc, created_at desc);
alter table public.inspections enable row level security;

drop policy if exists "read own inspections or admin" on public.inspections;
create policy "read own inspections or admin" on public.inspections
  for select to authenticated
  using (user_id = (select auth.uid()) or public.is_admin());

drop policy if exists "insert own inspections" on public.inspections;
create policy "insert own inspections" on public.inspections
  for insert to authenticated
  with check (user_id = (select auth.uid()));

-- ---------- inspection photos (files live in Storage, rows link them to a report) ----------
create table if not exists public.inspection_photos (
  id uuid primary key default gen_random_uuid(),
  inspection_id uuid not null references public.inspections (id) on delete cascade,
  path text not null unique,
  created_at timestamptz not null default now()
);
create index if not exists idx_photos_inspection on public.inspection_photos (inspection_id);
alter table public.inspection_photos enable row level security;

drop policy if exists "read photos of visible inspections" on public.inspection_photos;
create policy "read photos of visible inspections" on public.inspection_photos
  for select to authenticated
  using (exists (
    select 1 from public.inspections i
    where i.id = inspection_id and (i.user_id = (select auth.uid()) or public.is_admin())
  ));

drop policy if exists "add photos to own inspections" on public.inspection_photos;
create policy "add photos to own inspections" on public.inspection_photos
  for insert to authenticated
  with check (
    path like (select auth.uid())::text || '/%'
    and exists (
      select 1 from public.inspections i
      where i.id = inspection_id and i.user_id = (select auth.uid())
    )
  );

grant select on public.profiles to authenticated;
grant select, insert on public.inspections to authenticated;
grant select, insert on public.inspection_photos to authenticated;

-- ---------- dashboard stats (runs with the caller's RLS, so officers get their own numbers) ----------
create or replace function public.dashboard_stats()
returns json
language sql
stable
security invoker
set search_path = ''
as $$
  select json_build_object(
    'total_inspections', (select count(*) from public.inspections),
    'high_priority', (select count(*) from public.inspections where priority = 'High'),
    'districts_covered', (select count(distinct district) from public.inspections),
    'districts', coalesce((
      select json_agg(json_build_object('name', district, 'count', c) order by c desc, district)
      from (select district, count(*) as c from public.inspections group by district) d
    ), '[]'::json)
  );
$$;
revoke execute on function public.dashboard_stats() from public, anon;
grant execute on function public.dashboard_stats() to authenticated;

-- ---------- storage bucket for photos (private, 10 MB, images only) ----------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('inspection-photos', 'inspection-photos', false, 10485760,
        array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do nothing;

-- Files are stored as <user_id>/<inspection_id>/<file>, so the first folder is the owner.
drop policy if exists "upload own inspection photos" on storage.objects;
create policy "upload own inspection photos" on storage.objects
  for insert to authenticated
  with check (
    bucket_id = 'inspection-photos'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );

drop policy if exists "read own inspection photos or admin" on storage.objects;
create policy "read own inspection photos or admin" on storage.objects
  for select to authenticated
  using (
    bucket_id = 'inspection-photos'
    and ((storage.foldername(name))[1] = (select auth.uid())::text or public.is_admin())
  );

